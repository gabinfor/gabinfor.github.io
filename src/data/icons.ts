export type IconName = keyof typeof ICONS;

/** Run-length rects for one icon: [x, y, width]. */
export function iconRects(name: IconName): [number, number, number][] {
  const out: [number, number, number][] = [];
  ICONS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      const s = x;
      while (row[x] === '#') x++;
      out.push([s, y, x - s]);
    }
  });
  return out;
}
